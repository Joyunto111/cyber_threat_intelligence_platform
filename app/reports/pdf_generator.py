"""Professional PDF Threat Report Generator using ReportLab."""

import os
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable, KeepTogether
)

REPORTS_DIR = Path(__file__).resolve().parent.parent.parent / "data" / "reports"
REPORTS_DIR.mkdir(parents=True, exist_ok=True)


class PDFReportGenerator:
    """Generates executive-ready PDF threat intelligence assessment reports."""

    def __init__(self):
        self.styles = getSampleStyleSheet()
        self._setup_custom_styles()

    def _setup_custom_styles(self):
        self.styles.add(ParagraphStyle(
            name="ReportTitle",
            parent=self.styles["Heading1"],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0f172a"),
            fontName="Helvetica-Bold",
            spaceAfter=6
        ))
        self.styles.add(ParagraphStyle(
            name="ReportSubtitle",
            parent=self.styles["Normal"],
            fontSize=11,
            leading=15,
            textColor=colors.HexColor("#475569"),
            spaceAfter=15
        ))
        self.styles.add(ParagraphStyle(
            name="SectionHeading",
            parent=self.styles["Heading2"],
            fontSize=13,
            leading=17,
            textColor=colors.HexColor("#1e293b"),
            fontName="Helvetica-Bold",
            spaceBefore=12,
            spaceAfter=8
        ))
        self.styles.add(ParagraphStyle(
            name="BodySmall",
            parent=self.styles["Normal"],
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#334155")
        ))
        self.styles.add(ParagraphStyle(
            name="DisclaimerText",
            parent=self.styles["Normal"],
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#64748b"),
            fontName="Helvetica-Oblique"
        ))

    def generate(self, analyses: List[Dict[str, Any]], title: str = "Cyber Threat Intelligence Assessment") -> str:
        """Renders and saves a PDF threat report. Returns the file path."""
        timestamp_str = datetime.utcnow().strftime("%Y%m%d_%H%M%S")
        filename = f"CTI_Report_{timestamp_str}.pdf"
        file_path = REPORTS_DIR / filename

        doc = SimpleDocTemplate(
            str(file_path),
            pagesize=letter,
            rightMargin=36,
            leftMargin=36,
            topMargin=36,
            bottomMargin=36
        )

        story = []

        # Header Title
        story.append(Paragraph(title, self.styles["ReportTitle"]))
        sub_text = f"Generated by CTI Analysis Platform | Date: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')} | Indicators Assessed: {len(analyses)}"
        story.append(Paragraph(sub_text, self.styles["ReportSubtitle"]))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceAfter=14))

        # Iterate over each assessed indicator
        for idx, item in enumerate(analyses):
            risk = item.get("risk_assessment", {})
            r_score = risk.get("risk_score", 0.0)
            r_cat = risk.get("risk_category", "UNKNOWN")
            c_score = risk.get("confidence_score", 0.0)
            threat_class = risk.get("threat_classification", "UNKNOWN")

            # Risk color badge
            badge_color = colors.HexColor("#16a34a")  # Green
            if r_cat == "CRITICAL":
                badge_color = colors.HexColor("#dc2626")  # Red
            elif r_cat == "HIGH":
                badge_color = colors.HexColor("#ea580c")  # Orange
            elif r_cat == "MEDIUM":
                badge_color = colors.HexColor("#d97706")  # Amber

            story.append(Paragraph(f"Indicator #{idx+1}: {item.get('defanged', item.get('indicator'))}", self.styles["SectionHeading"]))

            # Primary Metrics Table
            metrics_data = [
                [
                    Paragraph("<b>Raw Value:</b>", self.styles["BodySmall"]),
                    Paragraph(item.get("indicator", ""), self.styles["BodySmall"]),
                    Paragraph("<b>Risk Score:</b>", self.styles["BodySmall"]),
                    Paragraph(f"<b><font color='{badge_color.hexval()}'>{r_score}/100 ({r_cat})</font></b>", self.styles["BodySmall"])
                ],
                [
                    Paragraph("<b>IOC Type:</b>", self.styles["BodySmall"]),
                    Paragraph(item.get("indicator_type", ""), self.styles["BodySmall"]),
                    Paragraph("<b>Confidence:</b>", self.styles["BodySmall"]),
                    Paragraph(f"{c_score}%", self.styles["BodySmall"])
                ],
                [
                    Paragraph("<b>Defanged:</b>", self.styles["BodySmall"]),
                    Paragraph(item.get("defanged", ""), self.styles["BodySmall"]),
                    Paragraph("<b>Classification:</b>", self.styles["BodySmall"]),
                    Paragraph(threat_class, self.styles["BodySmall"])
                ]
            ]

            t_metrics = Table(metrics_data, colWidths=[1.1*inch, 2.5*inch, 1.1*inch, 2.3*inch])
            t_metrics.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                ('TOPPADDING', (0, 0), (-1, -1), 4),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(t_metrics)
            story.append(Spacer(1, 8))

            # Intelligence Evidence Table
            explanations = risk.get("explanations", [])
            if explanations:
                story.append(Paragraph("<b>Evidence & Analytical Findings:</b>", self.styles["BodySmall"]))
                evidence_data = [["Factor", "Impact", "Evidence Summary", "Intelligence Source"]]
                for exp in explanations[:6]:
                    pts = exp.get("points_impact", 0)
                    evidence_data.append([
                        exp.get("factor", ""),
                        f"+{pts}" if pts > 0 else f"{pts}",
                        Paragraph(exp.get("evidence", ""), self.styles["BodySmall"]),
                        exp.get("source", "")
                    ])
                t_evidence = Table(evidence_data, colWidths=[1.5*inch, 0.7*inch, 3.4*inch, 1.4*inch])
                t_evidence.setStyle(TableStyle([
                    ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                    ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                    ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                    ('FONTSIZE', (0, 0), (-1, 0), 8),
                    ('BOTTOMPADDING', (0, 0), (-1, 0), 4),
                    ('BACKGROUND', (0, 1), (-1, -1), colors.white),
                    ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                    ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ]))
                story.append(t_evidence)
                story.append(Spacer(1, 8))

            # Defensive Actions
            actions = risk.get("recommended_actions", [])
            if actions:
                story.append(Paragraph("<b>Recommended Defensive Countermeasures:</b>", self.styles["BodySmall"]))
                for act in actions[:4]:
                    story.append(Paragraph(f"• {act}", self.styles["BodySmall"]))
                story.append(Spacer(1, 10))

            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=10))

        # Limitations and Methodology Disclaimer
        story.append(Spacer(1, 10))
        disclaimer = (
            "<b>Methodology & Limitations Disclaimer:</b> Threat intelligence data is gathered from official feeds, "
            "DNS infrastructure, and heuristic models. The absence of an external API detection must never be treated "
            "as conclusive proof that an indicator is benign. Machine learning predictions (such as DGA and phishing classifiers) "
            "are heuristic signals designed for analyst triage and must not be cited as confirmed malicious telemetry without "
            "substantive corroboration. Generated by Cyber Threat Intelligence Platform."
        )
        story.append(Paragraph(disclaimer, self.styles["DisclaimerText"]))

        doc.build(story)
        return str(file_path)


pdf_generator = PDFReportGenerator()
