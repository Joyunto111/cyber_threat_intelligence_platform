    def evaluate_dga_domain(self, domain: str) -> Dict[str, Any]:
        """Evaluates whether a domain is likely generated by a Domain Generation Algorithm (DGA).

        Uses lexical statistical indicators: entropy, vowel-to-consonant ratio, length, n-gram patterns.
        """
        parts = domain.lower().split(".")
        sld = parts[0] if len(parts) >= 2 else domain

        entropy = shannon_entropy(sld)
        length = len(sld)
        digits = sum(c.isdigit() for c in sld)
        vowels = sum(c in "aeiou" for c in sld)
        consonants = sum(c.isalpha() and c not in "aeiou" for c in sld)

        vowel_ratio = (vowels / max(consonants, 1))
        has_long_consonant_cluster = bool(re.search(r'[bcdfghjklmnpqrstvwxyz]{5,}', sld))

        # Algorithmic scoring
        dga_score = 0.0
        signals = []

        if entropy > 3.8:
            dga_score += 0.4
            signals.append(f"High Shannon entropy ({entropy})")
        if vowel_ratio < 0.25 and consonants > 5:
            dga_score += 0.35
            signals.append(f"Abnormally low vowel-to-consonant ratio ({vowel_ratio:.2f})")
        if has_long_consonant_cluster:
            dga_score += 0.25
            signals.append("Consecutive non-pronounceable consonant clusters detected")
        if length > 16:
            dga_score += 0.15
            signals.append(f"Extended domain label length ({length} characters)")
        if digits > 4:
            dga_score += 0.2
            signals.append(f"Elevated digit count ({digits} digits in label)")

        is_dga = dga_score >= 0.55
        confidence = min(0.95, round(dga_score, 2))

        return {
            "is_dga": is_dga,
            "confidence": confidence,
            "entropy": entropy,
            "sld": sld,
            "signals": signals,
            "assessment": "Synthetic DGA Pattern Detected" if is_dga else "Likely Human-Readable Domain"
        }

    def evaluate_phishing_url(self, url: str) -> Dict[str, Any]:
        """Extracts lexical features and predicts phishing likelihood."""
        u_lower = url.lower()
        phish_score = 0.0
        flags = []

        # Feature 1: Sensitive targeting keywords in path or query
        sensitive_keywords = [
            "login", "signin", "verify", "secure", "banking", "account",
            "update", "confirm", "wallet", "password", "credential", "session"
        ]
        matched_kw = [kw for kw in sensitive_keywords if kw in u_lower]
        if matched_kw:
            phish_score += min(0.4, len(matched_kw) * 0.15)
            flags.append(f"Sensitive phishing keywords observed: {', '.join(matched_kw)}")

        # Feature 2: IP address used as URL host
        if re.search(r'https?://(?:\d{1,3}\.){3}\d{1,3}', u_lower):
            phish_score += 0.35
            flags.append("Bare IP address utilized as target host")

        # Feature 3: Excessive URL length or deep path
        if len(url) > 80:
            phish_score += 0.2
            flags.append(f"Abnormal URL length ({len(url)} characters)")

        # Feature 4: Deceptive subdomain structures (e.g. paypal.com.attacker.com)
        for brand in TARGET_BRANDS:
            if brand in u_lower:
                # Check if brand is not the primary domain
                domain_match = re.search(r'https?://([^/]+)', u_lower)
                if domain_match:
                    host = domain_match.group(1)
                    if brand in host and not host.endswith(f".{brand}.com") and host != f"{brand}.com":
                        phish_score += 0.45
                        flags.append(f"Brand impersonation pattern targeting '{brand.upper()}'")
                        break

        # Feature 5: Suspicious character counts (@ symbol, double slashes in path)
        if "@" in url:
            phish_score += 0.3
            flags.append("Use of '@' delimiter to obfuscate destination credentials")

        is_phishing = phish_score >= 0.45
        confidence = min(0.95, round(phish_score, 2))

        return {
            "is_phishing": is_phishing,
            "confidence": confidence,
            "flags": flags,
            "assessment": "High-Risk Phishing Heuristics" if is_phishing else "Low Phishing Likelihood"
        }

    def detect_anomalies(self, ioc_value: str, ioc_type: str) -> List[str]:
        """Detects anomalous structural traits or brand impersonation."""
        anomalies = []
        val_lower = ioc_value.lower()

        if ioc_type == "DOMAIN":
            parts = val_lower.split(".")
            tld = parts[-1] if len(parts) > 1 else ""
            if tld in SUSPICIOUS_TLDS:
                anomalies.append(f"Registered on high-abuse top-level domain (.{tld})")

            # Check typosquatting against major brands
            sld = parts[0] if len(parts) >= 2 else val_lower
            for brand in TARGET_BRANDS:
                dist = levenshtein_distance(sld, brand)
                if 1 <= dist <= 2 and sld != brand:
                    anomalies.append(f"Possible typosquatting / brand spoofing of '{brand}' (Levenshtein distance {dist})")

        elif ioc_type == "URL":
            # Suspicious executable or script extensions
            if re.search(r'\.(exe|scr|bat|vbs|ps1|hta|iso|apk|dll|jar)(\?|$)', val_lower):
                anomalies.append("Direct link to executable payload or script distribution")

        return anomalies

    def generate_natural_language_summary(
        self,
        ioc_value: str,
        ioc_type: str,
        risk_score: float,
        risk_category: str,
        confidence_score: float,
        classification: str,
        explanations: List[Dict[str, Any]],
        recommendations: List[str]
    ) -> str:
        """Produces an analyst-ready narrative intelligence summary."""
        lines = []
        lines.append(f"### Threat Intelligence Assessment: {ioc_value}")
        lines.append(f"**Classification:** `{classification}` | **Risk Score:** `{risk_score}/100` ({risk_category}) | **Confidence:** `{confidence_score}%`\n")

        if risk_category in ("CRITICAL", "HIGH"):
            lines.append(
                f"**Executive Brief:** Indicator `{ioc_value}` represents a confirmed high-priority cybersecurity threat. "
                f"Corroborated intelligence sources and analytical telemetry classify this artifact under **{classification}**. "
                f"Active defensive mitigation is strongly recommended to protect internal infrastructure."
            )
        elif risk_category == "MEDIUM":
            lines.append(
                f"**Executive Brief:** Indicator `{ioc_value}` exhibits suspicious or anomalous characteristics. "
                f"While verified malicious activity is not definitively established by all engines, observed heuristic "
                f"and community markers warrant active operational monitoring."
            )
        else:
            lines.append(
                f"**Executive Brief:** Indicator `{ioc_value}` currently exhibits low risk indicators. "
                f"No verified malicious telemetry or hostile threat campaigns were detected across queried intelligence datasets."
            )

        if explanations:
            lines.append("\n**Key Intelligence Findings:**")
            for exp in explanations[:4]:
                lines.append(f"- **{exp.get('factor', 'Signal')}:** {exp.get('evidence', '')} *(Source: {exp.get('source')})*")

        if recommendations:
            lines.append("\n**Immediate Defensive Countermeasures:**")
            for action in recommendations[:3]:
                lines.append(f"1. {action}")

        return "\n".join(lines)


